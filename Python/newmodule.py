# add function
def add(a, b):
    return a + b

#subtract function
def subtract(a, b):
    return a - b

#multiply function
def multiply(a, b):
    return a * b

#divide function
def divide(a, b):
    if b == 0:
        return "Error: Division by zero is not allowed."
    return a / b
